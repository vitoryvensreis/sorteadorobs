CREATE DATABASE IF NOT EXISTS sorteadorobs CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE sorteadorobs;
CREATE TABLE IF NOT EXISTS admins (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS participants (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 phone VARCHAR(11) NOT NULL,
 cpf_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 cpf_ciphertext VARCHAR(255) NOT NULL,
 consented_at DATETIME NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 won_at DATETIME(3) NULL,
 INDEX idx_won (won_at), INDEX idx_phone (phone)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS lottery_state (
 id TINYINT UNSIGNED PRIMARY KEY,
 draw_seq BIGINT UNSIGNED NOT NULL DEFAULT 0,
 reset_seq BIGINT UNSIGNED NOT NULL DEFAULT 0,
 last_winner_id BIGINT UNSIGNED NULL,
 last_draw_at DATETIME(3) NULL,
 FOREIGN KEY(last_winner_id) REFERENCES participants(id) ON DELETE SET NULL
) ENGINE=InnoDB;
INSERT IGNORE INTO lottery_state (id) VALUES (1);
CREATE TABLE IF NOT EXISTS draws (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 participant_id BIGINT UNSIGNED NOT NULL,
 drawn_at DATETIME(3) NOT NULL,
 FOREIGN KEY(participant_id) REFERENCES participants(id) ON DELETE CASCADE,
 INDEX idx_drawn (drawn_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rate_limits (
 bucket CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 hits INT UNSIGNED NOT NULL DEFAULT 1,
 expires_at DATETIME NOT NULL,
 INDEX idx_exp (expires_at)
) ENGINE=InnoDB;
